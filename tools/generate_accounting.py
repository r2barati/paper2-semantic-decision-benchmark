"""Derive experiment accounting from the saved episode files.

Every count that appears in the paper, the appendix or the design documents is
produced here, from data. The pre-September-2026 documents claimed six Phase-7
sensors and 4,320 episodes where the saved file held five and 3,600, and claimed
50 Phase-6 seeds where the saved file held 20; those errors survived because the
numbers were written by hand from design intent.

    python3 -m tools.generate_accounting            # print a table
    python3 -m tools.generate_accounting --write    # refresh docs/ACCOUNTING.md
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
RESULTS = ROOT / "results"

EXPERIMENTS = [
    ("R (retrieval)", RESULTS / "retrieval" / "retrieval_episodes.csv", "system"),
    ("C (controlled)", RESULTS / "phase7_classical_baseline" / "operational_results.csv", "sensor"),
    ("M (multi-echelon)", RESULTS / "phase8b_gym_confirmation" / "operational_results.csv", "sensor"),
    ("S (supply-side)", RESULTS / "phase9a_capacity_confirmation" / "operational_results.csv", "sensor"),
]


def read(path: Path) -> list:
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle))


def account(path: Path, source_col: str) -> dict:
    rows = read(path)
    seeds = {r["seed"] for r in rows}
    sources = {r[source_col] for r in rows}
    regimes = {r.get("regime", "") for r in rows}
    # Experiment R has no template axis: its candidate pool is generated per
    # seed rather than drawn from an authored template set, so reporting a
    # template count of 1 would be misleading. Say so instead.
    has_templates = any(r.get("template_id") for r in rows)
    templates = {r["template_id"] for r in rows} if has_templates else set()
    return {
        "episodes": len(rows),
        "seeds": len(seeds),
        "templates": len(templates) if has_templates else None,
        "sources": len(sources),
        "regimes": len(regimes),
        "paired_worlds": len(seeds) * len(templates) if has_templates else len(seeds),
        "source_names": sorted(sources),
    }


def phase9b_account() -> dict | None:
    base = RESULTS / "phase9b_robustness"
    if not base.exists():
        return None
    rows = []
    variants = set()
    for d in sorted(base.glob("*/")):
        f = d / "operational_results.csv"
        if f.exists():
            variants.add(d.name)
            rows.extend(read(f))
    if not rows:
        return None
    seeds = {r["seed"] for r in rows}
    templates = {r["template_id"] for r in rows}
    return {
        "episodes": len(rows),
        "seeds": len(seeds),
        "templates": len(templates),
        "sources": len({r["sensor"] for r in rows}),
        "variants": len(variants),
        "paired_worlds": len(seeds) * len(templates),
        "source_names": sorted({r["sensor"] for r in rows}),
    }


def render() -> str:
    lines = [
        "# Experiment accounting",
        "",
        "Generated by `python3 -m tools.generate_accounting --write`.",
        "Every number here is counted from a saved episode file, never from",
        "design intent. Do not edit by hand.",
        "",
        "`episodes` counts rows across all information sources. The number of",
        "distinct **paired worlds** is seeds x templates; it is not the episode",
        "count, and conflating the two overstates the effective sample size.",
        "",
        "| Experiment | Seeds | Templates | Regimes | Sources | Paired worlds | Episodes |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name, path, col in EXPERIMENTS:
        if not path.exists():
            lines.append(f"| {name} | _not generated_ | | | | | |")
            continue
        a = account(path, col)
        tmpl = "n/a (generated pool)" if a["templates"] is None else f"{a['templates']}"
        lines.append(
            f"| {name} | {a['seeds']} | {tmpl} | {a['regimes']} | "
            f"{a['sources']} | {a['paired_worlds']:,} | {a['episodes']:,} |"
        )
    b = phase9b_account()
    if b:
        lines.append(
            f"| B (boundary, {b['variants']} variants) | {b['seeds']} | {b['templates']} | "
            f"-- | {b['sources']} | {b['paired_worlds']:,} | {b['episodes']:,} |"
        )

    lines += ["", "## Information sources per experiment", ""]
    for name, path, col in EXPERIMENTS:
        if not path.exists():
            continue
        a = account(path, col)
        lines.append(f"- **{name}** ({a['sources']}): {', '.join(a['source_names'])}")
    if b:
        lines.append(f"- **B (boundary)** ({b['sources']}): {', '.join(b['source_names'])}")

    lines += [
        "",
        "## Corrections to previously published counts",
        "",
        "| Claim | Where | Actual |",
        "|---|---|---|",
        "| Phase 7: 6 sensors, 4,320 episodes | appendix Table 3 | 5 sensors, 3,600 episodes "
        "before the 2026 controls were added (see the table above for the current run) |",
        "| Phase 6: 50 seeds | `docs/BENCHMARK_DESIGN.md` | 20 seeds in the saved primary file |",
        "| Phase 8B: 4,320 independent pairs | appendix | 720 seed/template pairs per sensor |",
        "| Controlled horizon: 30 periods | `docs/BENCHMARK_DESIGN.md` | 40 periods (`P5_HORIZON`) |",
        "| Experiment A: two regimes, heuristic controller | `paper_sections/experiment_a.md` | "
        "three regimes, `CausalOptimizer` |",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.write:
        out = ROOT / "docs" / "ACCOUNTING.md"
        out.write_text(text)
        print(f"wrote {out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
